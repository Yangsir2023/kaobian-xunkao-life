export const COLD_EXAM_LEVELS = HUKOU_LEVELS;

/** 归档统计：给测试与界面头部用 */
export function coldExamStats() {
  const groups = COLD_EXAMS.groups;
  const items = groups.flatMap((g) => g.items || []);
  const byLevel = {};
  for (const l of HUKOU_LEVELS) {
    byLevel[l.key] = items.filter((i) => i.hukou === l.key).length;
  }
  return {
    groups: groups.length,
    items: items.length,
    byLevel,
    pending: (COLD_EXAMS.pending || []).length,
  };
}
