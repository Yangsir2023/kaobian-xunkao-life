/** 归档统计：给测试与界面头部用 */
export function hukouStats() {
  const items = HUKOU_GUIDE.items;
  const byLevel = {};
  for (const l of HUKOU_LEVEL_KEYS) byLevel[l] = items.filter((i) => i.level === l).length;
  return {
    items: items.length,
    byLevel,
    open: byLevel.open,
    sources: items.reduce((n, i) => n + 1 + (i.stats || []).length, 0),
  };
}
