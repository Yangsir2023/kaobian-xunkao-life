/**
 * 户籍口径对照：哪些考试「外地考生」能报。
 *
 * 立这个模块的起因很直接——用户要的是「全国范围内、不限户籍、我能报的考试」，
 * 而"不限户籍"这四个字在不同考试里的含义差别极大：
 *   - 国考是全国一张卷，户籍只在艰苦边远地区的倾斜政策里出现；
 *   - 三支一扶各省自己定，湖北不设门槛、别的省可能限本省生源；
 *   - 社区工作者基本卡本市户籍 / 居住证，但"应届毕业生"常常是例外口子；
 *   - 村官名义下的县级自招，同一份公告里"应届限本地、往届不限"这种反直觉写法都有。
 *
 * 所以这里不给"能不能报"的二元结论，只做三件事：
 *   1. 给每条考试标一个户籍口径级别（open / fresh / local / mixed）；
 *   2. 把结论的依据原文（quote）与来源链接附在每条上，可点开核对；
 *   3. 没核到明确条款的一律不写进来，并在 caveat 里说明"没出现 ≠ 限户籍"。
 */

